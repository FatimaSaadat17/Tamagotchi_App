CREATE TYPE status_type AS ENUM ('OPEN', 'DONE');
CREATE TYPE priority_type AS ENUM ('HIGH', 'MEDIUM', 'LOW');
CREATE TYPE importance_type AS ENUM ('IMPORTANT', 'ROUTINE');

CREATE TABLE tasks (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(100) NOT NULL,
    planned_date DATE NOT NULL,
    estimated_minutes INTEGER NOT NULL,
    status status_type NOT NULL DEFAULT 'OPEN',
    priority priority_type NOT NULL DEFAULT 'HIGH',
    importance importance_type NOT NULL DEFAULT 'IMPORTANT',
    CONSTRAINT tasks_title_not_blank CHECK (btrim(title) <> ''),
    CONSTRAINT tasks_estimated_minutes_positive CHECK (estimated_minutes > 0)
);

