CREATE TABLE calendar_events (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(120) NOT NULL CHECK (title ~ '[^[:space:]]'),
    starts_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ends_at TIMESTAMP WITH TIME ZONE NOT NULL,
    time_zone VARCHAR(80) NOT NULL,
    priority priority_type NOT NULL,
    importance importance_type NOT NULL,
    notes VARCHAR(1000),
    CONSTRAINT calendar_events_ordered_times CHECK (ends_at > starts_at)
);

CREATE INDEX calendar_events_starts_at_idx ON calendar_events (starts_at);

CREATE TABLE goals (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(120) NOT NULL CHECK (title ~ '[^[:space:]]'),
    period VARCHAR(10) NOT NULL CHECK (period IN ('WEEKLY', 'MONTHLY', 'YEARLY')),
    target INTEGER NOT NULL CHECK (target > 0),
    progress INTEGER NOT NULL DEFAULT 0,
    due_date DATE,
    CONSTRAINT goals_valid_progress CHECK (progress BETWEEN 0 AND target)
);

