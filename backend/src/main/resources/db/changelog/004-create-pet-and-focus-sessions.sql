CREATE TABLE focus_sessions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_id INTEGER NOT NULL REFERENCES pets (id),
    task_id INTEGER REFERENCES tasks (id) ON DELETE SET NULL,
    started_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ended_at TIMESTAMP WITH TIME ZONE,
    planned_minutes INTEGER NOT NULL CHECK (planned_minutes BETWEEN 1 AND 25),
    status VARCHAR(10) NOT NULL CHECK (status IN ('RUNNING', 'COMPLETED', 'CANCELLED')),
    apples_awarded INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT focus_sessions_lifecycle CHECK (
        (status = 'RUNNING' AND ended_at IS NULL AND apples_awarded = 0)
        OR (status = 'COMPLETED' AND ended_at >= started_at AND ended_at IS NOT NULL AND apples_awarded = 1)
        OR (status = 'CANCELLED' AND ended_at >= started_at AND ended_at IS NOT NULL AND apples_awarded = 0)
    )
);

CREATE UNIQUE INDEX focus_sessions_one_running_idx ON focus_sessions (pet_id) WHERE status = 'RUNNING';
CREATE INDEX focus_sessions_task_idx ON focus_sessions (task_id);

