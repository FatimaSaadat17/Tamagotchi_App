CREATE TABLE pets (
    id INTEGER PRIMARY KEY CHECK (id = 1),
    name VARCHAR(80) NOT NULL,
    fullness INTEGER NOT NULL CHECK (fullness BETWEEN 0 AND 5),
    health INTEGER NOT NULL CHECK (health BETWEEN 0 AND 5),
    happiness INTEGER NOT NULL CHECK (happiness BETWEEN 0 AND 5),
    apples INTEGER NOT NULL CHECK (apples >= 0),
    sick BOOLEAN NOT NULL,
    hunger_at TIMESTAMP WITH TIME ZONE NOT NULL
);

